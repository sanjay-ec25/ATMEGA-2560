#define PORTF_ADDR  0x31

/* PORT G */
#define PING_ADDR   0x32
#define DDRG_ADDR   0x33
#define PORTG_ADDR  0x34

/* PORT H */
#define PINH_ADDR   0x100
#define DDRH_ADDR   0x101
#define PORTH_ADDR  0x102

/* PORT J */
#define PINJ_ADDR   0x103
#define DDRJ_ADDR   0x104
#define PORTJ_ADDR  0x105

/* PORT K */
#define PINK_ADDR   0x106
#define DDRK_ADDR   0x107
#define PORTK_ADDR  0x108

/* PORT L */
#define PINL_ADDR   0x109
#define DDRL_ADDR   0x10A
#define PORTL_ADDR  0x10B

#endif
